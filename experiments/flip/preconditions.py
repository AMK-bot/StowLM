"""One-core, fail-closed pre-flip checklist; never flips or confers G1 evidence.

Default invocation reports unexecuted gates as FAIL; --list lists their suites.
--run-tests executes suites in fresh
OFF/ON contexts, serially. Reviews/operational prerequisites need a separately
source-bound leader checklist; unit test success never asserts physical yield.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from hashlib import sha256
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import time
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
THREAD_VARIABLES = ('OPENBLAS_NUM_THREADS', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS',
    'VECLIB_MAXIMUM_THREADS', 'NUMEXPR_NUM_THREADS', 'BLIS_NUM_THREADS')


def read(path):
    data = Path(path).read_bytes()
    return data, sha256(data).hexdigest()


def write(path, value):
    Path(path).write_text(json.dumps(value, indent=2, sort_keys=True)+'\n')


def source_identity(root=ROOT):
    """Code, fixtures, policies and tests; excludes generated bytecode/caches."""
    paths = set()
    for name in ('src', 'params', 'data/fixtures', 'tests'):
        base = root/name
        if base.exists():
            paths.update(path for path in base.rglob('*') if path.is_file()
                and '__pycache__' not in path.parts and path.suffix not in ('.pyc', '.pyo'))
    for name in ('pyproject.toml', 'uv.lock', 'experiments/fleet/TRACKS.md',
        'experiments/review/w2/STATUS.md'):
        if (root/name).is_file(): paths.add(root/name)
    for base in (root/'experiments/flip', root/'experiments/campaign-g1',
                 root/'experiments/gold-plans/campaign', root/'experiments/gold-plans/tiny'):
        if base.exists():
            paths.update(path for path in base.glob('*') if path.is_file()
                and path.suffix in ('.py', '.json', '.patch') and (base.name != 'flip' or path.suffix=='.py'
                    or path.name in ('version-plan.json', 'gate-suites.json',
                                    'activation.patch', 'activation-preimages.json')))
    for base in (root/'experiments/review/w2', root/'experiments/review/fixes/w2'):
        if base.exists(): paths.update(base.glob('*.md'))
    files = {path.relative_to(root).as_posix():read(path)[1] for path in sorted(paths)}
    digest = sha256(json.dumps(files, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return dict(sha256=digest, files=files)


def gate_paths(gate, root=ROOT):
    paths = set()
    for pattern in gate['patterns']:
        if Path(pattern).is_absolute() or '..' in Path(pattern).parts:
            raise ValueError('test path escapes repository')
        matched = [path for path in root.glob(pattern) if path.exists()]
        if not matched:
            raise ValueError(f'missing test suite: {pattern}')
        for path in matched:
            if not path.resolve().is_relative_to(root.resolve()):
                raise ValueError('test path symlink escapes repository')
            paths.add(path.relative_to(root).as_posix())
    if not paths:
        raise ValueError('empty test suite')
    return sorted(paths)


def require_resolved_versions(plan):
    unresolved = plan.get('unresolved_numeric_proposals', [])
    if unresolved:
        raise ValueError('unresolved numeric proposals: '+json.dumps(unresolved))


def review_check(gate, approval, source_sha, root=ROOT, phase='pre-flip'):
    reasons = []
    if approval.get('source_sha256') != source_sha:
        reasons.append('leader checklist absent or bound to another source/test epoch')
    item = approval.get('items', {}).get(gate['id'], {})
    if item.get('fixes_verified') is not True or not item.get('reviewer'):
        reasons.append('landed fixes/code+logic closure not confirmed by leader')
    for key in ('code_review', 'logic_review'):
        relative = gate.get(key)
        try:
            if not relative or item.get(key+'_sha256') != read(root/relative)[1]:
                reasons.append(key+' missing or changed')
        except OSError:
            reasons.append(key+' missing or unreadable')
    confirmed = item.get('requirements_confirmed', [])
    required = gate.get('pre_flip_requirements', gate.get('manual_requirements', []))
    if phase == 'post-flip': required = required + gate.get('post_flip_requirements', [])
    if confirmed != required:
        reasons.append('operational requirements not all confirmed; see runbook producer blockers')
    return reasons


def junit_result(path):
    tree = ET.parse(path).getroot()
    suites = [tree] if tree.tag == 'testsuite' else list(tree.iter('testsuite'))
    counts = {key:sum(int(suite.get(key, 0)) for suite in suites)
              for key in ('tests', 'failures', 'errors', 'skipped')}
    counts['executed'] = counts['tests']-counts['skipped']
    return counts


def run_gate(gate, output, *, modes=('off', 'on'), timeout_s=1800, root=ROOT):
    paths = gate_paths(gate, root)
    env = os.environ.copy()
    env.update({name:'1' for name in THREAD_VARIABLES})
    env.update(PYTHONDONTWRITEBYTECODE='1', UV_CACHE_DIR=str(root/'.uv-cache'))
    results = []
    for mode in modes:
        name = gate['id']+'-'+mode
        junit = output/(name+'.xml')
        command = ['uv', 'run', '--offline', '--no-sync', '--project', str(ROOT), 'python', str(HERE/'preconditions.py'),
            '__pytest__', mode, *paths, '-o', 'addopts=', '--import-mode=importlib',
            '-m', 'not slow and not gpu and not net', '-q', '--tb=short',
            '--basetemp='+str(output/(name+'-tmp')), '--junitxml='+str(junit)]
        started = time.monotonic()
        with (output/(name+'.log')).open('wb') as log:
            child = subprocess.Popen(command, cwd=root, env=env, stdin=subprocess.DEVNULL,
                stdout=log, stderr=subprocess.STDOUT)
            (output/(name+'.pid')).write_text(str(child.pid)+'\n')
            try:
                returncode = child.wait(timeout=timeout_s)
            except subprocess.TimeoutExpired:
                # Stop only the exact process launched here; never pattern-kill.
                child.terminate()
                try: child.wait(timeout=10)
                except subprocess.TimeoutExpired: child.kill(); child.wait()
                returncode = 124
        result = dict(mode=mode, command=command, pid=child.pid, returncode=returncode,
            wall_s=time.monotonic()-started, passed=False)
        try:
            result['junit'] = junit_result(junit)
            result['passed'] = (returncode == 0 and result['junit']['executed'] > 0
                and result['junit']['failures'] == result['junit']['errors'] == 0)
        except (OSError, ET.ParseError, ValueError) as error:
            result['error'] = f'no valid executed-test inventory: {error}'
        results.append(result)
        write(output/(name+'-result.json'), result)
    return results


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] == '__pytest__':
        if len(argv) < 4 or argv[1] not in ('off', 'on'):
            raise ValueError('invalid internal pytest invocation')
        for name in THREAD_VARIABLES: os.environ[name] = '1'
        import pytest
        from stowage.rules.catalogue import rule_freeze_v1
        with rule_freeze_v1(enabled=argv[1] == 'on'):
            return pytest.main(argv[2:])
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--list', action='store_true')
    parser.add_argument('--run-tests', action='store_true')
    parser.add_argument('--gate', action='append', default=[])
    parser.add_argument('--phase', choices=('pre-flip', 'post-flip'), default='pre-flip',
        help='Pre-flip checks code/reviews; qualified live evidence is deferred explicitly to post-flip.')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--approvals', type=Path)
    parser.add_argument('--write-approval-template', type=Path)
    parser.add_argument('--timeout-s', type=float, default=1800.)
    args = parser.parse_args(argv)
    if not math.isfinite(args.timeout_s) or args.timeout_s <= 0: parser.error('--timeout-s must be finite and positive')
    definitions = json.loads(read(HERE/'gate-suites.json')[0])
    gates = definitions['gates']
    unknown = set(args.gate)-{gate['id'] for gate in gates}
    if unknown: parser.error('unknown gates: '+','.join(sorted(unknown)))
    if args.gate: gates = [gate for gate in gates if gate['id'] in args.gate]
    if args.list:
        for gate in gates:
            print(gate['id']+': '+' '.join(gate_paths(gate)))
        return 0
    output = (args.output or HERE/('preflight-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ'))).resolve()
    if not output.is_relative_to(HERE): parser.error('output must stay under experiments/flip/')
    output.mkdir(parents=True, exist_ok=False)
    before = source_identity()
    write(output/'source-start.json', before)
    approval = json.loads(read(args.approvals)[0]) if args.approvals else {}
    if args.write_approval_template:
        target = args.write_approval_template.resolve()
        if not target.is_relative_to(HERE) or target.exists():
            parser.error('approval template must be a new file under experiments/flip/')
        items = {}
        for gate in gates:
            required = gate.get('pre_flip_requirements', gate.get('manual_requirements', []))
            if args.phase=='post-flip': required = required + gate.get('post_flip_requirements', [])
            item = dict(fixes_verified=False, reviewer='', requirements_confirmed=[],
                requirements_needed=required,
                deferred_until_post_flip=gate.get('post_flip_requirements', []) if args.phase=='pre-flip' else [])
            for key in ('code_review', 'logic_review'):
                relative = gate.get(key)
                item[key+'_sha256'] = read(ROOT/relative)[1] if relative and (ROOT/relative).is_file() else None
            items[gate['id']] = item
        write(target, dict(source_sha256=before['sha256'], items=items,
            warning='Leader checklist only. Does not execute or attest physics; no G1 evidence.'))
    rows = []
    from prepare_patch import verify
    try:
        patch = verify(ROOT)
        require_resolved_versions(json.loads(read(HERE/'version-plan.json')[0]))
        rows.append(dict(id='coordinated_patch', passed=True, detail=patch))
    except (OSError, ValueError, KeyError) as error:
        rows.append(dict(id='coordinated_patch', passed=False, reasons=[str(error)]))
    for gate in gates:
        reasons = review_check(gate, approval, before['sha256'], phase=args.phase)
        runs = []
        try:
            paths = gate_paths(gate)
            if args.run_tests: runs = run_gate(gate, output, timeout_s=args.timeout_s)
            else: reasons.append('test suites not executed; use --run-tests')
            if runs and not all(run['passed'] for run in runs): reasons.append('OFF/ON suite failed or executed no tests')
        except (OSError, ValueError) as error:
            paths = []; reasons.append(str(error))
        row = dict(id=gate['id'], title=gate['title'], passed=not reasons,
            reasons=reasons, tests=runs, paths=paths, manual_requirements=gate.get('manual_requirements', []),
            deferred_until_post_flip=gate.get('post_flip_requirements', []) if args.phase=='pre-flip' else [])
        rows.append(row)
        test_status = ('tests=PASS' if runs and all(run['passed'] for run in runs) else
                       'tests=FAIL' if runs else 'tests=NOT_RUN')
        print(('PASS' if row['passed'] else 'FAIL')+' '+row['id']+': '+test_status+'; '+
            ('; '.join(reasons) or 'reviews and OFF/ON suites complete'), flush=True)
        write(output/'progress.json', rows)
    after = source_identity()
    write(output/'source-end.json', after)
    rows.append(dict(id='source_unchanged', passed=before == after,
        reasons=[] if before == after else ['source/test/driver epoch changed during preflight']))
    all_ids = {gate['id'] for gate in definitions['gates']}
    complete = {gate['id'] for gate in gates} == all_ids
    report = dict(schema_version=1, diagnostic=True, evidence_eligible=False,
        applied=False, phase=args.phase, scope_complete=complete, source_sha256=before['sha256'],
        passed=complete and all(row['passed'] for row in rows), gates=rows,
        notes=['Preflight only; no qualification, canary execution, freeze, generation or G1 evidence.',
               'One serial test child at a time; one native numerical thread; no GPU/network tests.'])
    write(output/'report.json', report)
    for row in rows:
        if row['id'] in ('coordinated_patch', 'source_unchanged'):
            print(('PASS' if row['passed'] else 'FAIL')+' '+row['id']+
                (': '+'; '.join(row.get('reasons', [])) if row.get('reasons') else ''), flush=True)
    print(('PASS' if report['passed'] else 'FAIL')+' flip_preconditions (diagnostic checklist only)', flush=True)
    return 0 if report['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
