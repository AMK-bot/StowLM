"""Cold CP-SAT stow construction; global certificates remain certified.py's job.

The constructor restricts the existing final-stow relaxation to load-once ship
placements, so its first-aboard ranks can be emitted as real Place actions.
Yard relocations remain allowed and are generated by the ordinary expander.
An internal model bound is deliberately not returned as a global lift bound.
Every returned candidate has passed real replay; ballast and the independent
full checker remain mandatory after this stage.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import importlib.util
from pathlib import Path
import sys
from time import monotonic

from stowage.actions.space import Place
from stowage.model import Placement

HERE = Path(__file__).resolve().parent
SCOPE = ("fewest lifts among plans the checker passes, counting later ports by "
         "our D15 projection (fixed stow, no later loads)")


def install_e9():
    """Use only the process-local mask correction authorized by the contract."""
    name = "c4_hatch_constructor_e9fix"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, HERE.parents[1] / "c1/leader/e9fix.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    sys.modules[name].install()


@dataclass
class Construction:
    actions: tuple = ()
    replay_lifts: float | None = None
    wall_time_s: float = 0.
    status: str = "no_candidate"
    iterations: int = 0
    log: list = field(default_factory=list)
    cuts: list = field(default_factory=list)
    first_model_witness: dict | None = None
    first_model_actions: tuple = ()
    first_replay_witness: dict | None = None
    assignment: dict | None = None
    first_aboard_order: list | None = None
    family: str = "load_once_cold_construction_not_a_global_bound"
    full_checker_pass: bool = False


def build_constructor_model(instance, *, budget_s, seed=0, tables=None):
    """Retain safe DG widening and add constructive ship-order constraints."""
    from bound_joint import build_model
    context = build_model(instance, budget_s=budget_s, seed=seed, tables=tables)
    if isinstance(context, dict):
        for flag in context["ship_restowed"].values():
            context["model"].add(flag == 0)
    return context


def witness_actions(assignment, first_aboard_order, load_list):
    """Validate completeness and preserve the solver's support/hatch order."""
    order = list(first_aboard_order or [])
    if (set(assignment) != set(load_list) or len(order) != len(load_list)
            or set(order) != set(load_list)):
        raise ValueError("constructor witness must place every required box exactly once")
    return tuple(Place(bid, assignment[bid]) for bid in order)


def _exclude_ordered_witness(context, assignment, order):
    """Exclude only this assignment AND order after a replay rejection."""
    model, T, chosen = (context[k] for k in ("model", "T", "chosen"))
    alternatives = [chosen[T.box_index[bid], T.slot_index[slot]].Not()
                    for bid, slot in assignment.items()]
    for rank, bid in enumerate(order):
        differs = model.new_bool_var(f"replay_order_diff_{len(model.proto.variables)}")
        model.add(context["birth"][T.box_index[bid]] != rank).only_enforce_if(differs)
        alternatives.append(differs)
    model.add_bool_or(alternatives)


def _static_cuts(context, assignment, ship, violations):
    """Use exactly the C3 necessary static cuts; no checker rule is changed."""
    from lazy_bound import _cut, _e6_cut
    from geometry_cuts import add_heat, add_oog_pair
    cuts = []
    for violation in violations:
        ids = set(violation.containers) & set(assignment)
        if violation.rule_id == "expert.e6.heavy_under_deck":
            size = _e6_cut(context, assignment, ship, violation)
            if size is not None:
                cuts.append(dict(rule=violation.rule_id, kind="ordinary_e6_columns", size=size))
        elif violation.rule_id in {"expert.e8.away_from_heat", "expert.e9.over_width_length"} and ids:
            added = (any(add_heat(context, assignment, bid) for bid in ids)
                     if violation.rule_id == "expert.e8.away_from_heat"
                     else add_oog_pair(context, assignment, ids))
            if added:
                cuts.append(dict(rule=violation.rule_id, kind="outward_floor_disjunction", size=len(ids)))
    if not cuts:
        cuts.append(dict(rule=violations[0].rule_id, kind="full_final_assignment",
                         size=_cut(context, assignment, set(assignment))))
    return cuts


def construct(instance, *, budget_s=45., seed=0, problem=None, tables=None):
    """Return the first static-screened replay-legal exact-model candidate.

    No incumbent stow, incumbent ballast or map-specific data is consulted.
    The first optimization slice is at most eight seconds; an UNKNOWN solve
    subsequently receives the remaining time rather than identical restarts.
    This time-limited construction is not guaranteed complete.
    """
    import math
    from alns import Problem
    from bound_joint import solve_model
    from geometry_cuts import add_all_oog_pairs
    from securing_cuts import add_securing_cut
    from stowage.checker.rules import check_static_rules

    if not math.isfinite(budget_s) or budget_s <= 0:
        raise ValueError("budget_s must be positive and finite")
    started = monotonic()
    output = Construction()
    install_e9()
    context = build_constructor_model(instance, budget_s=budget_s, seed=seed, tables=tables)
    if not isinstance(context, dict):
        output.status = "unsupported_arrival_or_forecast"
        output.wall_time_s = monotonic() - started
        return output
    output.log.append(dict(eager_oog_pairs=add_all_oog_pairs(context),
                           safe_unary_domains=context["unary_info"]))
    problem = problem or Problem(instance)
    first_solve = True
    while budget_s - (monotonic() - started) > .01:
        remaining = budget_s - (monotonic() - started)
        context["solve_budget_s"] = min(8., max(.01, budget_s * .35)) if first_solve else remaining
        first_solve = False
        result = solve_model(context)
        output.iterations += 1
        row = dict(status=result.status, objective=result.relaxation_incumbent,
                   elapsed_s=monotonic() - started)
        output.log.append(row)
        assignment = result.relaxation_assignment
        if assignment is None:
            if result.status in {"infeasible", "model_invalid"}:
                output.status = "load_once_model_" + result.status
                break
            continue
        ship = instance.onboard.model_copy(update={"placements": [
            Placement(container_id=bid, slot=slot) for bid, slot in assignment.items()],
            "covers_off": {}})
        violations = [v for v in check_static_rules(instance, ship,
            call_index=instance.call_index).violations if v.severity == "hard"]
        row["static_violations"] = sorted({v.rule_id for v in violations})
        if output.first_model_witness is None:
            output.first_model_actions = witness_actions(
                assignment, result.first_aboard_order, instance.load_list)
            raw_scored = problem.score(output.first_model_actions)
            output.first_model_witness = dict(assignment=assignment,
                order=result.first_aboard_order, static_violations=row["static_violations"],
                objective=result.relaxation_incumbent,
                replay_legal=raw_scored is not None,
                replay_lifts=raw_scored.objective if raw_scored is not None else None)
        if violations:
            output.cuts.extend(_static_cuts(context, assignment, ship, violations))
            continue
        cut, securing = add_securing_cut(context, assignment, ship)
        row["securing_status"] = securing.get("status")
        if cut is not None:
            output.cuts.append(cut)
            continue
        actions = witness_actions(assignment, result.first_aboard_order, instance.load_list)
        scored = problem.score(actions)
        row["replay_legal"] = scored is not None
        if scored is None:
            _exclude_ordered_witness(context, assignment, result.first_aboard_order)
            output.cuts.append(dict(kind="replay_assignment_and_order", size=len(actions)))
            continue
        output.actions = actions
        output.assignment = assignment
        output.first_aboard_order = result.first_aboard_order
        output.replay_lifts = scored.objective
        output.first_replay_witness = dict(assignment=assignment, order=result.first_aboard_order,
            model_objective=result.relaxation_incumbent, replay_lifts=scored.objective,
            elapsed_s=monotonic() - started)
        output.status = "replay_legal_needs_ballast_and_full_checker"
        break
    output.wall_time_s = monotonic() - started
    return output
