"""rev-k1c fixes for K1C-CHANCE.md, as a new report over stored artifacts; no running arm reads this file. It verifies identity from the artifacts themselves, not from
DONE files, makes the port audit an admission condition for rule-masked arms, and puts timeout counts, judging windows and historical versions beside the comparisons.
Writes identity-check.json, then K1C-CHANCE.md. Any mismatch is printed and stops the report. Usage: chance_final.py [--check-only]
"""
from __future__ import annotations

from datetime import datetime
import hashlib
import json
from pathlib import Path
import sys

import k1b_report as r
import k1c_chance_report as q
import k1c_report as c
import pair_blockrule as b

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
ADAPTER = ROOT/'experiments/mvp/sft/stowlm-v2/adapter'
K1B = json.loads((HERE/'manifest.json').read_text())
# root, adapter expected, rule in the mask, generated by run_c1 (False: uniform random)
GENERATIONS = {'8.2 K1b': (HERE, True, False, True), 'null': (HERE/'null', False, False, True), 'K1r': (HERE/'k1r', False, False, False),
               '8.2 K1c': (HERE/'k1c', True, True, True), 'random K1c': (HERE/'k1c-random', False, True, False), 'null K1c': (HERE/'k1c-null', False, True, True)}
MASKED = {'8.2': '8.2 K1c', 'random': 'random K1c', 'null': 'null K1c'}
PLANNER = dict(temperature=.7, n_samples=16, backtrack=32, greedy_first=True, candidate_finalize_s=600.)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def text_sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def ready(name):
    return len(list((GENERATIONS[name][0]/'judged/model').glob('*.json'))) == 55


def config_problems(name, config, expect_adapter, inputs):
    found = []
    parameters = config['planner_parameters']
    if bool(parameters.get('adapter_path')) != expect_adapter:
        found.append(f"{name}: adapter_path {parameters.get('adapter_path')}")
    found += [f'{name}: {k} = {parameters.get(k)}' for k, v in PLANNER.items() if parameters.get(k) != v]
    if config['seed'] != 0 or config['allow_repair'] or config['active_stubs']:
        found.append(f"{name}: seed, repair or stubs differ")
    found += [f"{name}: input {i['path']}" for i in config['inputs'] if inputs.get(i['path']) != i['sha256']]
    return found


def sample_problems(name, iid, samples, model_arm):
    found = []
    if sorted(samples) != [f'sample-{i:02d}.json' for i in range(16)]:
        return [f'{name} {iid}: {len(samples)} samples']
    for i, key in enumerate(sorted(samples)):
        s = json.loads(samples[key])
        temperature = (0. if i == 0 else .7) if model_arm else 'uniform'
        if s['sample'] != i or s['seed'] != i or s['temperature'] != temperature or s['instance_id'] != iid or (s['plan'] is None) != (s['status'] != 'complete'):
            found.append(f'{name} {iid}: sample {i} identity')
    return found


def verify_generation(name):
    import port_mask
    from stowage.io import load_instance
    from stowage.model import MovePlan
    root, adapter, masked, model_arm = GENERATIONS[name]
    inputs, found = K1B['inputs'], []
    found += [f'input changed: {f}' for f, h in inputs.items() if sha(ROOT/f) != h]
    if model_arm:
        configs = sorted(root.glob('decode/s*/config.json'))
        if not configs:
            found.append(f'{name}: no decode config')
        seen = []
        for path in configs:
            config = json.loads(path.read_text())
            found += config_problems(name, config, adapter, inputs)
            seen += [i['path'] for i in config['inputs']]
        if sorted(seen) != sorted(inputs):
            found.append(f'{name}: decode covers {len(seen)} inputs')
    audited = 0
    for row_path in sorted((root/'judged/model').glob('*.json')):
        row = json.loads(row_path.read_text())
        iid = row['instance_id']
        raw = {p.name: p.read_text() for p in sorted((root/'candidates'/iid).glob('sample-*.json'))}
        found += sample_problems(name, iid, raw, model_arm)
        binding = row['binding']
        if binding['samples_sha256'] != text_sha(json.dumps(raw, sort_keys=True)):
            found.append(f'{name} {iid}: candidates differ from the judged row')
        if binding['input_sha256'] != inputs.get(row['input']):
            found.append(f'{name} {iid}: judged input')
        winner = row.get('winner')
        if winner:
            plan, report = root/'judged/plans'/f'{iid}.json', root/'judged/plans'/f'{iid}.report.json'
            if not plan.exists() or sha(plan) != winner['plan_sha256'] or sha(report) != winner['report_sha256']:
                found.append(f'{name} {iid}: winner artifact')
        if masked:
            instance = load_instance(ROOT/row['input'])
            for text in raw.values():
                sample = json.loads(text)
                if sample['plan'] is not None:
                    audited += 1
                    if port_mask.audit(instance, MovePlan.model_validate(sample['plan'])):
                        found.append(f"{name} {iid}: stored sample {sample['sample']} breaks the rule")
    return dict(problems=found, rule_audited_candidates=audited)


def adapter_identity():
    return [f'adapter file {p.name} differs from K1b' for p in sorted(ADAPTER.iterdir()) if p.is_file() and sha(p) != K1B['adapter'].get(p.name)]


def verify_kcurve():
    """Binds each k-curve and first-sample row to its candidates and judged row, and checks that an imported verdict concerned the same compacted cost."""
    import compact
    import judge
    from stowage.io import load_instance
    from stowage.model import MovePlan
    arms = {'8.2': HERE, 'null': HERE/'null', 'K1r': HERE/'k1r', 'first/8.2': HERE/'k1c', 'first/random': HERE/'k1c-random', 'first/null': HERE/'k1c-null'}
    folders = {'8.2': HERE/'kcurve/8.2', 'null': HERE/'kcurve/null', 'K1r': HERE/'kcurve/K1r', 'first/8.2': HERE/'k1c-greedy/8.2', 'first/random': HERE/'k1c-greedy/random', 'first/null': HERE/'k1c-greedy/null'}
    found, checked = [], 0
    for arm, folder in folders.items():
        for path in sorted(folder.glob('*.json')):
            row = json.loads(path.read_text())
            iid, root = row['instance_id'], arms[arm]
            raw = {p.name: p.read_text() for p in sorted((root/'candidates'/iid).glob('sample-*.json'))}
            judged_path = root/'judged/model'/f'{iid}.json'
            judged = json.loads(judged_path.read_text())
            first = arm.startswith('first/')
            if first and row['binding']['sample_sha256'] != text_sha(raw['sample-00.json']):
                found.append(f'{arm} {iid}: first sample differs')
            if not first and row['binding']['samples_sha256'] != text_sha(json.dumps(raw, sort_keys=True)):
                found.append(f'{arm} {iid}: candidates differ')
            if judged_path.stat().st_mtime > path.stat().st_mtime:
                found.append(f'{arm} {iid}: judged row is newer than the cache')
            instance = load_instance(ROOT/judged['input'])
            for trial in judged['trials']:
                sample = json.loads(raw[f"sample-{trial['sample']:02d}.json"])
                plan = MovePlan.model_validate(sample['plan'])
                compacted, info = compact.compact_plan(instance, plan)
                better = compacted is not None and info['compact_raw']['total'] < info['before']['total']
                cost = info['compact_raw']['total'] if better else info['before']['total']
                checked += 1
                if cost != trial['cost'] or better != trial['compacted']:
                    found.append(f"{arm} {iid}: trial {trial['sample']} compacts differently now")
    return dict(problems=found, trials_recomputed=checked, code={n: judge.sha_file(HERE.parent/n if n == 'compact.py' else HERE/n) for n in ('compact.py', 'judge.py', 'kcurve.py')})


def admit_rule(moves, audits):
    """A rule-masked winner counts only with an empty audit; the audit never touches the unconstrained fallback."""
    return {i: (v if v is None or not audits.get(i) else None) for i, v in moves.items()}


def exposure(root):
    rows = q.rows(root/'judged/model')
    trials = [t for x in rows.values() for t in x['trials']]
    times = sorted(p.stat().st_mtime for p in (root/'judged/model').glob('*.json'))
    stamp = lambda t: datetime.fromtimestamp(t).strftime('%d %b %H:%M')
    code = {json.dumps(x['binding'].get('code'), sort_keys=True) for x in rows.values()}
    version = 'pre-rev-k1b rows, no code binding' if code == {'null'} else ', '.join(sorted(v[:8] for x in code for v in json.loads(x).values()))
    return dict(trials=len(trials), timed_out=sum(bool(t.get('timed_out')) for t in trials), window=f'{stamp(times[0])}–{stamp(times[-1])}', version=version)


def write(identity):
    from stowage.io import load_instance
    from stowage.model import PlannerResult
    import port_mask
    q.write()
    text = (HERE/'K1C-CHANCE.md').read_text()
    audits = {}
    for arm, name in MASKED.items():
        if ready(name):
            root, found = GENERATIONS[name][0], {}
            for x in q.rows(root/'judged/model').values():
                if x['moves'] is not None:
                    plan = PlannerResult.model_validate(json.loads((root/'judged/plans'/f"{x['instance_id']}.json").read_text())).plan
                    found[x['instance_id']] = port_mask.audit(load_instance(ROOT/x['input']), plan)
            audits[arm] = found
    trained = q.rows(q.UNCONSTRAINED['8.2'])
    table = b.blockrule_rows(b.SOURCE.read_text())
    rule = {i: table[b.map_name(x['input'])] for i, x in trained.items()}
    lines = ['', '## Admission: port audit of every rule-masked winner', '',
             'A rule-masked winner counts only with an empty audit, separately from the declared fallback, which is unconstrained by design. If any winner is rejected, the tables above overstate that arm and the row here governs.', '',
             '| Arm | Winners audited | Rejected | Rule-masked alone after admission, vs block-rule | K1c after admission, vs block-rule |', '|---|---:|---:|---|---|']
    for arm, found in audits.items():
        masked = admit_rule(q.moves(q.rows(q.ARMS[arm]/'judged/model')), found)
        p, s = r.pair(masked, rule), r.pair(c.with_fallback(masked, q.moves(q.rows(q.UNCONSTRAINED[arm]))), rule)
        show = lambda x: f"{x['mine']}/55, {'—' if x['delta'] is None else format(x['delta']*100, '+.1f')+' %'} on {x['mutual']}"
        lines.append(f"| {q.LABEL[arm]} | {len(found)} | {sum(bool(v) for v in found.values())} | {show(p)} | {show(s)} |")
    lines += ['', '## Exposure beside each comparison', '',
              'The arms share the nominal 600 s finisher but not the judging window, the machine load or the script version. A timeout rejects a cheaper candidate and can select a costlier one, so close differences here may be timing and not skill. Windows are row publication times, not trial telemetry; no arm has matched or quiet-load evidence.', '',
              '| Arm | Trials | Hit the finisher limit | Judged (EDT) | Judge + compaction version |', '|---|---:|---:|---|---|']
    for name in GENERATIONS:
        if ready(name):
            e = exposure(GENERATIONS[name][0])
            lines.append(f"| {name} | {e['trials']} | {e['timed_out']} ({e['timed_out']/e['trials']*100:.0f} %) | {e['window']} | {e['version']} |")
    lines += ['', '## Identity check at report time', '',
              f"Verified from the artifacts, not from DONE files: input bytes against K1b's frozen hashes, the adapter directory against K1b's, each decode config (adapter or none, 16 samples, T = 0.7, greedy first, 32 rewinds, seed 0, no repair), every sample's index, seed and temperature, candidates against judged-row bindings, winner plan and report digests, and for rule-masked arms a port audit of all {identity['rule_audited_candidates']} stored complete candidates. "
              f"K-curve and first-sample rows: bound to candidates and judged rows, with {identity['trials_recomputed']} judged trials recompacted to the same cost. **Mismatches: {len(identity['problems'])}.**", '']
    (HERE/'K1C-CHANCE.md').write_text(text+'\n'.join(lines))


def main():
    names = [n for n in GENERATIONS if ready(n)]
    problems, audited = adapter_identity(), 0
    for name in names:
        result = verify_generation(name)
        problems += result['problems']
        audited += result['rule_audited_candidates']
    curves = verify_kcurve()
    problems += curves['problems']
    identity = dict(checked=datetime.now().astimezone().isoformat(), arms=names, problems=problems, rule_audited_candidates=audited,
                    trials_recomputed=curves['trials_recomputed'], code=curves['code'])
    (HERE/'identity-check.json').write_text(json.dumps(identity, indent=1)+'\n')
    print(json.dumps(dict(arms=names, mismatches=len(problems), rule_audited=audited, trials=curves['trials_recomputed'])), flush=True)
    for problem in problems[:40]:
        print('MISMATCH', problem, flush=True)
    if problems:
        raise SystemExit('identity mismatch: K1C-CHANCE.md not rewritten')
    if '--check-only' not in sys.argv:
        write(identity)


if __name__ == '__main__':
    main()
