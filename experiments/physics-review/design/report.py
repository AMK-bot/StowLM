"""Render results_<label>.json (+ sweep_results.json) into conditions.md tables.

Run: uv run python experiments/physics-review/design/report.py [label ...]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
B23 = [("containership_area_0_30_mrad", "area_0_30_mrad", "B2.3 area 0-30"),
       ("containership_area_0_40_mrad", "area_0_40_mrad", "B2.3 area 0-40"),
       ("containership_area_30_40_mrad", "area_30_40_mrad", "B2.3 area 30-40"),
       ("containership_gz_at_or_above_30_m", "gz_at_or_above_30_m", "B2.3 GZ>=30"),
       ("containership_gz_max_m", "gz_max_m", "B2.3 GZmax"),
       ("containership_area_0_flood_mrad", "area_0_flood_mrad", "B2.3 area 0-flood")]


def f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def criteria(r):
    """(criterion, value, limit, pass) rows; limit = value - margin where margin = value - limit."""
    rows = []
    st = r["parts"]["stability"]
    m, g = st["metrics"], st["margins"]
    if st["ran"]:
        rows.append(("GM0 (m)", m["gm_m"], m["gm_m"] - g["gm_m"], g["gm_m"] >= 0))
        for mk, vk, label in B23:
            if mk in g:
                rows.append((label, m[vk], m[vk] - g[mk], g[mk] >= -1e-12))
        rows.append(("weather ratio b/a", m.get("weather_ratio"), 1.0, g.get("weather_ratio", -1) >= -1e-12))
        rows.append(("weather steady heel margin (rad)", g.get("weather_steady_heel_margin_rad"), 0.0,
                     g.get("weather_steady_heel_margin_rad", -1) >= -1e-12))
        rows.append(("weather table applicable", 1.0 + g.get("weather_table_applicability", -1), 1.0,
                     g.get("weather_table_applicability", -1) >= -1e-12))
        rows.append(("|trim| (m)", abs(m["trim_m"]), abs(m["trim_m"]) + g["trim_m"], g["trim_m"] >= 0))
        rows.append(("|list| (rad)", abs(m["list_rad"]), abs(m["list_rad"]) + g["list_rad"], g["list_rad"] >= 0))
        rows.append(("draught aft (m) vs max", m["draught_aft_m"], m["draught_aft_m"] + g["draught_aft_m"],
                     g["draught_aft_m"] >= 0))
        rows.append(("draught fwd (m) vs min", m["draught_fwd_m"], m["draught_fwd_m"] - g["draught_fwd_min_m"],
                     g["draught_fwd_min_m"] >= 0))
    sg = r["parts"]["strength"]
    if sg["ran"] and sg["margins"]:
        rows.append(("SF/permissible (max)", sg["margins"].get("sf_ratio"), 1.0, sg["margins"].get("sf_ratio", 9) <= 1))
        rows.append(("BM/permissible (max)", sg["margins"].get("bm_ratio"), 1.0, sg["margins"].get("bm_ratio", 9) <= 1))
    vi = r["parts"]["visibility"]
    if vi["ran"] and vi["metrics"]:
        rows.append(("blind distance (m)", vi["metrics"].get("blind_distance_m"), vi["metrics"].get("limit_m"),
                     vi["margins"].get("blind_distance_m", -1) >= 0))
    la = r["parts"]["lashing"]
    if la["ran"]:
        worst = min(la["margins"].items(), key=lambda kv: kv[1]) if la["margins"] else None
        if worst:
            rows.append((f"lashing worst margin [{worst[0]}]", worst[1], 0.0, worst[1] >= 0))
    else:
        rows.append(("lashing", None, None, False))
    ru = r["parts"]["rules"]
    if "stack_mass_kg" in ru["margins"]:
        rows.append(("stack mass margin (kg, min)", ru["margins"]["stack_mass_kg"], 0.0, ru["margins"]["stack_mass_kg"] >= 0))
    return rows


def render(labels):
    out = ["# Loading-manual design conditions (C1-C4) — production checker", "",
           "Generated by `report.py` from `results_<label>.json` (harness.py). Value / limit; FAIL rows only in the",
           "short table, full criteria below. Assumptions: see harness.py docstring and README.md.", ""]
    for label in labels:
        path = HERE / f"results_{label}.json"
        if not path.exists():
            continue
        res = json.loads(path.read_text())
        out += [f"## Run `{label}`", "",
                "| Ship | Cond | Boxes (hold/deck, ashore) | t/box | Δ (t) | finisher | passed | failing criteria (value / limit) | check s | finisher s |",
                "|---|---|---|---:|---:|---|---|---|---:|---:|"]
        for r in res:
            fails = [f"{c} {f(v)}/{f(l)}" for c, v, l, ok in criteria(r) if not ok]
            other = sorted({v["rule"] for p in r["parts"].values() for v in p["violations"]
                            if not v["rule"].startswith(("iscode", "strength"))})
            out.append(f"| {r['vessel']} | {r['condition']} | {r['boxes']} ({r['boxes_hold']}/{r['boxes_deck']}, {r['left_ashore']}) | "
                       f"{r['mean_box_kg']/1e3:.1f} | {r['displacement_kg']/1e3:.0f} | {r['finisher']['status']} | "
                       f"{'PASS' if r['passed'] else 'FAIL'} | {'; '.join(fails) or '–'}{' + ' + ', '.join(other) if other else ''} | "
                       f"{r['check_s']:.1f} | {r['finisher']['wall_s']:.1f} |")
        out.append("")
        for r in res:
            out += [f"### {r['vessel']} {r['condition']} ({label})", "",
                    f"Δ {r['displacement_kg']/1e3:.0f} t (design {r['design_displacement_kg']/1e3:.0f} t), cargo {r['cargo_mass_kg']/1e3:.0f} t, "
                    f"consumables {r['consumables_fraction']:.0%}, ballast {sum(r['ballast_kg'].values())/1e3:.0f} t, finisher {r['finisher']['status']}"
                    f" ({r['finisher']['iterations']} evals).", "",
                    "| Criterion | Value | Limit | |", "|---|---:|---:|---|"]
            for c, v, l, ok in criteria(r):
                out.append(f"| {c} | {f(v,4)} | {f(l,4)} | {'ok' if ok else '**FAIL**'} |")
            pr = r.get("probe_all_wb_full")
            if pr and pr["stability"]["ran"]:
                pm = pr["stability"]["metrics"]
                out.append(f"\nProbe, every WB tank pressed full ({pr['ballast_total_kg']/1e3:.0f} t): GM {f(pm['gm_m'])} m, "
                           f"trim {f(pm['trim_m'])} m, GZmax {f(pm['gz_max_m'])} m.")
            out.append("")
    sweep = HERE / "sweep_results.json"
    if sweep.exists():
        rows = json.loads(sweep.read_text())
        out += ["## Sensitivity sweep (stability only)", "",
                "| Ship | Point | VCG (m, /D) | WB cap (t) | Cond | Ballast | GM (m) | KG (m) | GZmax | weather | GM ok | B2.3 ok | weather ok | s |",
                "|---|---|---|---:|---|---|---:|---:|---:|---:|---|---|---|---:|"]
        for r in rows:
            out.append(f"| {r['vessel']} | {r['point']} | {r['lightship_vcg_m']:.2f} ({r['vcg_frac_depth']:.2f}) | {r['wb_capacity_t']:.0f} | "
                       f"{r['condition']} | {r['ballast']} | {f(r['gm_m'])} | {f(r['kg_m'])} | {f(r['gz_max_m'])} | "
                       f"{f(r['weather_ratio'],2)} | {'y' if r['gm_ok'] else 'n'} | {'y' if r['b23_ok'] else 'n'} | "
                       f"{'y' if r['weather_ok'] else 'n'} | {r['seconds']:.1f} |")
        out.append("")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    labels = sys.argv[1:] or ["before", "after"]
    (HERE / "conditions_tables.md").write_text(render(labels))
    print((HERE / "conditions_tables.md").read_text()[:3000])
