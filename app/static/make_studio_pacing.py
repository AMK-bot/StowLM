"""Generate app/static/studio-pacing.js (the paced take's beat table) from the narration and run sheet.

    uv run python app/static/make_studio_pacing.py

Inputs: experiments/mvp/video/studio-demo/narration.json (segments: id, step, title, target_s, lead_in_s) and the
"**Hold:**" lines of RUNSHEET.md (the first "about N s" in each segment). Starts are cumulative target_s, in film time
(0 = the Dock click). Not served: the server only serves allow-listed studio*.js/css names.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEMO = ROOT / "experiments/mvp/video/studio-demo"
OUT = Path(__file__).with_name("studio-pacing.js")


def holds(runsheet: str) -> dict[int, float]:
    out = {}
    for block in re.split(r"\n### ", runsheet)[1:]:
        head = re.match(r"(\d+)", block)
        hold = re.search(r"\*\*Hold:\*\*[^\n]*?about ([\d.]+) s", block)
        if head and hold:
            out[int(head.group(1))] = float(hold.group(1))
    return out


def main() -> None:
    narration = json.loads((DEMO / "narration.json").read_text())
    hold = holds((DEMO / "RUNSHEET.md").read_text())
    at, rows = 0.0, []
    for seg in narration["segments"]:
        rows.append({"id": seg["id"], "step": seg["step"], "title": seg["title"], "start_s": round(at, 2),
                     "target_s": seg["target_s"], "lead_in_s": seg.get("lead_in_s", 0), "hold_s": hold.get(seg["id"], 2.0)})
        at += seg["target_s"]
    table = {"source": "experiments/mvp/video/studio-demo/narration.json + RUNSHEET.md", "open_s": 2.0, "total_s": round(at, 2), "segments": rows}
    OUT.write_text("/* GENERATED by app/static/make_studio_pacing.py from " + table["source"] + ". Do not edit.\n"
                   " * Film time: 0 = the Dock click; the window shows the home screen at open_s. */\n"
                   "window.StudioPacing = " + json.dumps(table, indent=1) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} segments, {table['total_s']} s")


if __name__ == "__main__":
    main()
