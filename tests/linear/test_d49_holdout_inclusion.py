"""Scheme-1 history: D49 row inclusion on 576 independently recorded physical states.

The exact equilibria are checkpointed fresh experiment evidence, not generated by
the affine model under test. Check every pin/domain before reusing them. This
is a finite-population regression, not a universal error-bound proof or a
full-checker departure certificate. The exact archived epoch is retained;
these observations are never presented as scheme-2 qualification. Live scheme-2
admission and analytic row fixtures run in test_scheme2_evidence_migration.
"""
from dataclasses import asdict
import hashlib
import importlib.util
import json
from pathlib import Path

import numpy as np
import pytest

from stowage.linear import build_linear_model, linear_constraints
from stowage.linear.bands import band_for_instance
from tests.linear._scheme1_replay import open_context


ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "experiments/linear-model/epoch_requalification/production-1028b"
EVIDENCE_HASH_SCHEME = '1'
HISTORY = open_context(EVIDENCE,EVIDENCE_HASH_SCHEME)
# Deliberately replay immutable qualification files under their historical IDs.
from stowage.conventions import VESSEL_ID_ALIASES
LEGACY_MIDDLE = next(old for old, new in VESSEL_ID_ALIASES.items() if new == "feeder_800")
SHIPS = ("feeder_500", LEGACY_MIDDLE, "feeder_1700")
LEVELS = ("light", "medium", "full")


def _digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                    allow_nan=False).encode()).hexdigest()


@pytest.fixture(scope="module")
def physical_driver():
    return HISTORY


def _inside(value, lower, upper):
    value = np.asarray(value)
    return bool(np.all(value >= np.asarray(lower)-1e-7)
                and np.all(value <= np.asarray(upper)+1e-7))


@pytest.mark.parametrize("ship", SHIPS)
@pytest.mark.parametrize("level", LEVELS)
def test_physical_holdouts_have_required_row_inclusions(physical_driver, ship, level):
    source_path = EVIDENCE / "ordinary" / ship / f"holdout-{level}.json"
    replay_path = EVIDENCE / "holdout-audit/replay" / ship / f"{level}.json"
    source = json.loads(source_path.read_text())
    replay = json.loads(replay_path.read_text())
    current = physical_driver.snapshot(ship, physical_driver.prepare(ship)[0].parameters)
    assert source["phase"] == "holdout"
    assert source["samples"] == len(source["list_row_samples"]) == 64
    assert source["physical_inputs_unchanged"] is True
    assert source["physical_inputs_start"] == source["physical_inputs_end"] == current
    assert replay["complete"] is True
    assert replay["expected_samples"] == len(replay["states"]) == 64
    assert replay["input_binding"]["physical_inputs"] == replay["physical_inputs_end"] == current
    assert replay["input_binding"]["source"] == {
        "path": str(source_path.relative_to(ROOT)),
        "sha256": hashlib.sha256(source_path.read_bytes()).hexdigest(),
    }
    assert replay["input_binding"]["states_sha256"] == _digest(source["list_row_samples"])

    model = physical_driver.ordinary_model(ship, level, source)
    assert json.loads(json.dumps(asdict(model.band))) == source["band"]
    tables = {direction: physical_driver.constraints(model, direction=direction)
              for direction in ("necessary", "conservative")}
    policy = model.measurement_diagnostics["loading_policy"]
    band = model.band
    exact_gm_passes = conservative_gm_passes = 0
    for index, (state, replayed) in enumerate(zip(source["list_row_samples"], replay["states"], strict=True)):
        assert replayed["index"] == index
        assert replayed["sample_sha256"] == _digest(state)
        exact = replayed["exact"]
        assert source["sample_state_exact_source"]["format"] == 1
        for metric in ("gm_m", "displacement_kg", "trim_m", "list_rad", "draught_m", "sf_n", "bm_nm"):
            np.testing.assert_array_equal(exact[metric], state["exact_"+metric])
        cells, tanks = np.asarray(state["cell_masses_kg"]), np.asarray(state["tank_masses_kg"])
        trim, draught = exact["trim_m"], exact["draught_m"]
        exact_rows = {
            "gm": _inside(exact["gm_m"], model.gm_min_m, np.inf),
            "trim": _inside(trim, max(policy["min_trim_m"], -band.max_abs_trim_m),
                            min(policy["max_trim_m"], band.max_abs_trim_m)),
            "draught": _inside(draught, band.draught_min_m, band.draught_max_m),
            "draught_aft": _inside(draught+trim/2, -np.inf, model.hull_max_draught_m),
            "draught_forward": _inside(draught-trim/2, model.hull_min_draught_fwd_m, model.hull_max_draught_m),
            "displacement": _inside(exact["displacement_kg"],
                max(policy["min_displacement_kg"], band.displacement_min_kg),
                min(policy["max_displacement_kg"], band.displacement_max_kg)),
        }
        heel = min(model.max_list_rad, band.max_abs_heel_rad)
        exact_rows["list_port"] = _inside(exact["list_rad"], -np.inf, heel)
        exact_rows["list_starboard"] = _inside(exact["list_rad"], -heel, np.inf)
        if model._cargo_mass_kg is not None:
            exact_rows["cargo_mass"] = _inside(cells.sum(), model._cargo_mass_kg, model._cargo_mass_kg)
        for key, (lower, upper) in model._tank_mass_bounds_kg.items():
            exact_rows[f"tank_mass@{key}"] = _inside(tanks[model.tank_ids.index(key)], lower, upper)
        exact_gm_passes += exact_rows["gm"]
        for direction, table in tables.items():
            values = table.a_cell@cells + table.a_tank@tanks + table.const
            passes = (values >= table.lb-1e-7) & (values <= table.ub+1e-7)
            if direction == "conservative":
                conservative_gm_passes += bool(passes[table.names.index("gm")])
            strength_indices = {"sf": 0, "bm": 0}
            for name, accepted in zip(table.names, passes, strict=True):
                context = (ship, level, index, direction, name)
                if name.startswith(("sf@", "bm@")):
                    # Distinct stations can share a six-significant-digit :g
                    # label. Preserve coefficient-array order and every row.
                    kind = name[:2]
                    i = strength_indices[kind]
                    assert name == f"{kind}@{model.station_x_m[i]:g}", context
                    strength_indices[kind] += 1
                    unit = "n" if kind == "sf" else "nm"
                    exact_passed = _inside(exact[kind+"_"+unit][i],
                        getattr(model, kind+"_min_"+unit)[i],
                        getattr(model, kind+"_max_"+unit)[i])
                else:
                    exact_passed = exact_rows[name]
                if direction == "necessary":
                    assert accepted or not exact_passed, context
                else:
                    assert exact_passed or not accepted, context
            assert strength_indices == {"sf":len(model.station_x_m),"bm":len(model.station_x_m)}
    # Establish nonempty accepted/exact populations; an empty set would make
    # even a broken conservative GM model appear to satisfy inclusion.
    assert exact_gm_passes > 0
    assert conservative_gm_passes > 0
